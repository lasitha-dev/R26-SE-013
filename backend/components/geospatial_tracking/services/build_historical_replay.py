"""Checkpoint 4 / 4.5 orchestrator: coordinate-collision status, historical
event dates, target quality tiers, chronology, forecast-origin ledger,
source snapshots, forecast targets, walk-forward fold candidates, and
dataset-freeze metadata — all generated reproducibly from Checkpoint
2.5's conservative canonical dataset (never from raw source files
directly, and never mutating them).

Run locally (never in CI — local_data/ is gitignored and not present in
the repo, same convention as build_canonical.py):

    cd backend
    python -m components.geospatial_tracking.services.build_historical_replay \
        ../local_data/pistes_raw ../local_data/processed/canonical_outbreaks_conservative.csv \
        ../local_data/manifests/model_candidate_report.csv ../local_data/manifests 14

Writes:
    <manifest_dir>/canonical_spatial_independence.csv  (Checkpoint 4, SUPERSEDED — kept for provenance, see below)
    <manifest_dir>/coordinate_collision_report.csv     (Checkpoint 4.5 Part 1-3 — authoritative going forward)
    <manifest_dir>/target_quality_report.csv           (Checkpoint 4, SUPERSEDED — NOT regenerated by this version)
    <manifest_dir>/target_quality_report_v2.csv         (Checkpoint 4.5 Part 5 — authoritative going forward)
    <manifest_dir>/historical_chronology.csv
    <manifest_dir>/historical_forecast_origins.csv      (includes the Part-7 source snapshot columns)
    <manifest_dir>/historical_forecast_targets.csv
    <manifest_dir>/walk_forward_fold_candidates.csv     (Checkpoint 4.5 Part 13)
    <manifest_dir>/dataset_freeze_manifest.json

METHODOLOGICAL HISTORY, NOT SILENTLY OVERWRITTEN (master-prompt Part 15):
`canonical_spatial_independence.csv` used a misleadingly-named boolean
(coordinate uniqueness called "spatial independence" — see
`services/coordinate_collision.py`'s module docstring for exactly why
that overstated the evidence). This orchestrator still generates it
(unchanged code, `services/canonical_spatial.py`), so a prior run's file
on disk is reproducible and comparable, but `coordinate_collision_report.csv`
is the corrected, authoritative artifact from Checkpoint 4.5 onward.
Likewise `target_quality_report.csv`'s old boolean-based schema is no
longer regenerated by this version of the orchestrator — the file may
still exist on disk from a Checkpoint 4 run for comparison, but
`target_quality_report_v2.csv` (STRICT/RESOLVED_ONLY tier variants) is
authoritative going forward.

`active_window_days` (the 5th CLI arg) is an EXPLICIT UNFROZEN_DEVELOPMENT_PARAMETER
— never claimed scientifically correct, see config.py / REPOSITORY_DESIGN.md.

COUNTRY_SCOPE NOTE (master-prompt Checkpoint 4.5 Part 9): every
per-country breakdown this script produces (chronology, origins, folds) is
a SURVEILLANCE/DATA-REPLAY BOUNDARY for how this corpus happens to be
organized — never a claim that disease transmission stops at a national
border. No cross-border epidemiological modeling exists in this
checkpoint or anywhere in this component yet.
"""

