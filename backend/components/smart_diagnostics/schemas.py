from pydantic import BaseModel, ConfigDict, Field, StrictBool, model_validator
from typing import List, Dict, Optional, Literal


class ClinicalObservations(BaseModel):
    """Reported clinical findings; unknown is distinct from an examined negative."""
    model_config = ConfigDict(extra="forbid")
    disease: Literal["foot_and_mouth", "mastitis"]
    vet_confirmed: StrictBool = False
    milk_abnormal: Optional[StrictBool] = None
    udder_inflammation: Optional[StrictBool] = None
    systemic_illness: Optional[StrictBool] = None
    affected_feet: Optional[int] = Field(default=None, ge=0, le=4, strict=True)
    mouth_lesion_cm: Optional[float] = Field(default=None, ge=0, allow_inf_nan=False, strict=True)
    appetite: Optional[Literal["normal", "reduced", "none"]] = None
    mentation: Optional[Literal["normal", "slightly_dull", "depressed"]] = None
    heel_and_coronary_involved: Optional[StrictBool] = None
    unable_to_stand: Optional[StrictBool] = None

    @model_validator(mode="after")
    def check_disease_fields(self):
        mastitis = ("milk_abnormal", "udder_inflammation", "systemic_illness")
        fmd = ("affected_feet", "mouth_lesion_cm", "appetite", "mentation", "heel_and_coronary_involved", "unable_to_stand")
        other = fmd if self.disease == "mastitis" else mastitis
        if any(getattr(self, name) is not None for name in other):
            raise ValueError("Observations contain findings for a different disease checklist.")
        return self


class Detection(BaseModel):
    bbox: List[float]
    confidence: float
    class_name: str


class BoundingBoxNormalized(BaseModel):
    x1: float
    y1: float
    x2: float
    y2: float


class BestDetection(BaseModel):
    bbox: List[float]
    confidence: float
    bbox_normalized: BoundingBoxNormalized


class Disease(BaseModel):
    name: str
    confidence: float
    all_probabilities: Dict[str, float]


class SeverityMetrics(BaseModel):
    # Clinical rules use ordinal 1/2/3 (or null); legacy image scores retain their scale.
    score: Optional[float] = 0.0
    grade: str  # "Severe" | "Moderate" | "Mild" | "Unassessable" | legacy baseline values
    description: Optional[str] = None  # Comprehensive clinical severity narrative generated by LLM
    prognosis: Optional[str] = None  # Clinical prognosis
    diagnostic_rationale: Optional[str] = None  # Dynamic diagnostic rationale from LLM reasoning
    spatial_correlation: Optional[str] = None  # Dynamic image-specific anatomical spatial correlation
    lesion_coverage_pct: Optional[float] = None
    cluster_count: Optional[int] = None
    mean_intensity: Optional[float] = None
    formatted: Optional[str] = None  # e.g. "Severe"
    source: Optional[str] = "llm_reasoning"  # includes "clinical_rules" for FMD/mastitis
    confidence_level: Optional[str] = "High"  # Clinical rules explicitly use "Not validated".
    needs_review: bool = False
    attention_coverage_pct: Optional[float] = None
    attention_cluster_count: Optional[int] = None
    top2_margin: Optional[float] = None
    composite_score: Optional[float] = None
    rubric_id: Optional[str] = None
    assessment_status: Optional[str] = None
    assessment_target: Optional[str] = None
    evidence: List[str] = Field(default_factory=list)
    missing_observations: List[str] = Field(default_factory=list)
    references: List[Dict[str, str]] = Field(default_factory=list)
    clinical_observations: Optional[ClinicalObservations] = None


class SegmentationAssessment(BaseModel):
    status: Literal["unavailable", "failed", "skipped", "completed_no_regions", "completed_with_regions"]
    lesion_coverage_pct: Optional[float] = None
    cluster_count: Optional[int] = None
    lesion_pixels: Optional[int] = None
    mean_intensity: Optional[float] = None
    analyzed_pixels: Optional[int] = None
    denominator: str = "analyzed_crop_pixels"
    policy_version: str = "crop_mask_v1"
    threshold: Optional[float] = None
    min_region_fraction: Optional[float] = None
    connectivity: Optional[int] = None
    contract_status: str = "training_lineage_unverified"
    error_code: Optional[str] = None


class ReviewAssessment(BaseModel):
    required: bool = False
    reasons: List[str] = Field(default_factory=list)
    policy_version: str = "image_review_v1_unvalidated"


class DetectResponse(BaseModel):
    cattle_detected: bool
    detections: List[Detection]
    best_detection: Optional[BestDetection]
    disease: Optional[Disease]
    severity: Optional[SeverityMetrics] = None
    segmentation: Optional[SegmentationAssessment] = None
    review: ReviewAssessment = Field(default_factory=ReviewAssessment)
    crop_transform: Optional[Dict] = None
    body_site: Optional[str] = None
    observed_symptoms: Optional[str] = None
    attention_image: Optional[str] = None
    model_metadata: Optional[Dict] = None
    spatial_correlation: Optional[str] = None
    cropped_image: Optional[str]
    symptoms_image: Optional[str] = None
    image_size: Optional[Dict[str, int]]
    device: Optional[str]


